

# 1. Git (작업의 기록을 남기는 내 컴퓨터의 기록 프로그램)
# Git은 구글 드라이브의 '버전 관리' 기능이나 한글/워드 프로그램의 '이전 저장 시점으로 되돌리기' 기능이 매우 강력하게 특화된 기록 도구

# 히스토리 기록 (세밀한 저장): 단순히 파일을 저장하는 것이 아니라, "누가, 언제, 어떤 코드를 수정했는지"를 스냅샷처럼 남길 수 있음.

# 시간 여행: 프로젝트를 진행하다가 심각한 오류가 발생했을 때, 어제 혹은 1주일 전의 완벽했던 상태로 소스 코드를 정확히 되돌릴 수 있음.

# 가지치기 (Branch): 원본 파일은 그대로 둔 채, 새로운 실험적인 기능을 추가해보고 싶을 때 '가지(Branch)'를 쳐서 따로 작업한 뒤 나중에 합칠 수 있음.

# 2. GitHub (내 기록을 보관하고 공유하는 '클라우드 저장소')
# GitHub는 Git으로 기록한 데이터들을 인터넷상에 올리는 온라인 보관소

# 온라인 백업: 내 컴퓨터가 고장 나더라도 GitHub에 코드를 올려두었다면 언제든 다시 내려받을 수 있음.

# 협업의 장: 구글 문서(Google Docs)를 공유하여 여러 명이 동시에 수정하듯, GitHub를 통해 전 세계 개발자들과 하나의 프로젝트를 함께 만들 수 있음.

# 포트폴리오: 내가 어떤 공부를 했고 어떤 프로젝트를 만들어왔는지 보여주는 '개발자의 이력서' 역할 수행